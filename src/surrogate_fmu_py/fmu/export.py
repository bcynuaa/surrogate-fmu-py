from __future__ import annotations

from typing import List, Tuple
from dataclasses import dataclass, field


@dataclass(frozen=True)
class FMUExportOprtions:
    fmi_version: int = 2 # fmi2 or fmi3
    fmi_type: str = "cs" # cs or me
    platforms: Tuple[str] = field(default_factory=lambda: ("win64-x64", ))
    model_name: str = "surrogate_fmu"
    model_identifier: str = "surrogate_fmu"
    input_names: List[str] = field(default_factory=list)
    output_names: List[str] = field(default_factory=list)
    initial_values: List[float] = field(default_factory=list)
    step_size: float = 0.1
    description: str = "A surrogate FMU generated by surrogate_fmu_py"
    pass