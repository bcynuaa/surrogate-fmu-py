from __future__ import annotations

import os
import tempfile
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, List, Mapping, Sequence
from xml.etree import ElementTree

from .description import FMIModelDescription, build_model_description, build_variables
from .injection import FMUInjector
from .injection.binary import FMUBinary, get_binary


@dataclass(frozen=True)
class FMUExportOptions:
    fmi_version: int = 2
    fmi_interface: str = "cs"
    platforms: List[str] = field(default_factory=lambda: ["win64-x64"])
    model_name: str = "surrogate_fmu"
    model_identifier: str = "surrogate_fmu"
    initial_values: Sequence[float] | None = None
    step_size: float = 0.1
    description: str = "A surrogate FMU generated by surrogate_fmu_py"
    @classmethod
    def from_dict(cls, data: Mapping[str, Any]) -> FMUExportOptions:
        return cls(
            fmi_version=data.get("fmi_version", 2),
            fmi_interface=data.get("fmi_interface", "cs"),
            platforms=data.get("platforms", ["win64-x64"]),
            model_name=data.get("model_name", "surrogate_fmu"),
            model_identifier=data.get("model_identifier", "surrogate_fmu"),
            initial_values=data.get("initial_values"),
            step_size=data.get("step_size", 0.1),
            description=data.get("description", "A surrogate FMU generated by surrogate_fmu_py"),
        )
        pass
    pass


@dataclass(frozen=True)
class _ExportSpec:
    binary: FMUBinary
    token: str
    input_names: List[str]
    output_names: List[str]
    require_initial_values: bool
    initial_names: List[str]
    initial_values: List[float]
    export_artifacts_func: Callable[[Path], object]
    pass


def _names(value: Any, field_name: str, count: int | None = None) -> List[str]:
    if isinstance(value, (str, bytes)) or not isinstance(value, Sequence):
        raise TypeError(f"{field_name} must be a sequence of names")
        pass
    names: List[str] = list(value)
    if (count is not None and len(names) != count) or any(not isinstance(name, str) or not name for name in names):
        expected = f"{count} " if count is not None else "only "
        raise ValueError(f"{field_name} must contain {expected}nonempty strings")
        pass
    return names
    pass


def _spec(raw: Mapping[str, Any]) -> _ExportSpec:
    required: set[str] = {
        "binary", "token", "input_names", "output_names",
        "require_initial_values", "initial_names", "initial_values", "export_artifacts_func",
    }
    missing: set[str] = required - raw.keys()
    if missing:
        raise ValueError(f"fmu_export_spec is missing: {sorted(missing)}")
        pass
    if not isinstance(raw["binary"], str) or not raw["binary"]:
        raise ValueError("fmu_export_spec['binary'] must name a registered binary")
        pass
    binary: FMUBinary = get_binary(raw["binary"])
    if not isinstance(raw["token"], str) or not raw["token"].strip():
        raise ValueError("fmu_export_spec['token'] must be a nonempty string")
        pass
    if type(raw["require_initial_values"]) is not bool:
        raise TypeError("fmu_export_spec['require_initial_values'] must be bool")
        pass
    require_initial_values: bool = raw["require_initial_values"]
    if require_initial_values != binary.require_initial_values():
        raise ValueError(f"{binary.binary_name()} requires require_initial_values={binary.require_initial_values()}")
        pass
    input_names: List[str] = _names(raw["input_names"], "input_names")
    output_names: List[str] = _names(raw["output_names"], "output_names")
    if not input_names or not output_names:
        raise ValueError("fmu_export_spec input_names and output_names must not be empty")
        pass
    initial_names: List[str] = _names(raw["initial_names"], "initial_names", len(output_names)) if require_initial_values else []
    if not require_initial_values and raw["initial_names"] not in (None, [], ()):
        raise ValueError("initial_names must be absent when require_initial_values is False")
        pass
    values = raw["initial_values"]
    if values is None:
        initial_values: List[float] = []
        pass
    elif isinstance(values, (str, bytes)) or not isinstance(values, Sequence):
        raise TypeError("initial_values must be a sequence or None")
        pass
    else:
        initial_values = list(values)
        pass
    if not require_initial_values and initial_values:
        raise ValueError("initial_values must be absent when require_initial_values is False")
        pass
    if not callable(raw["export_artifacts_func"]):
        raise TypeError("export_artifacts_func must be callable")
        pass
    export_artifacts_func: Callable[[Path], object] = raw["export_artifacts_func"]
    return _ExportSpec(
        binary=binary, token=raw["token"],
        input_names=input_names, output_names=output_names,
        require_initial_values=require_initial_values, initial_names=initial_names,
        initial_values=initial_values, export_artifacts_func=export_artifacts_func,
    )
    pass


def export(
    spec: Mapping[str, Any],
    path: str | Path,
    options: FMUExportOptions | None = None,
) -> Path:
    '''
    Export a completed fmu_export_spec mapping as an FMU.
    '''
    options = options if options is not None else FMUExportOptions()
    if not isinstance(options, FMUExportOptions):
        raise TypeError("options must be FMUExportOptions")
        pass
    if not isinstance(spec, Mapping):
        raise TypeError("spec must be the mapping returned by fmu_export_spec()")
        pass
    export_spec: _ExportSpec = _spec(spec)
    initial_values: Sequence[float] = (
        options.initial_values if options.initial_values is not None else export_spec.initial_values
    )
    variables = build_variables(
        input_names=export_spec.input_names,
        output_names=export_spec.output_names,
        require_initial_values=export_spec.require_initial_values,
        initial_names=export_spec.initial_names,
        initial_values=initial_values,
        include_time=options.fmi_version == 3,
    )
    model: FMIModelDescription = FMIModelDescription(
        model_name=options.model_name,
        model_identifier=options.model_identifier,
        token=export_spec.token,
        variables=variables,
        fmi_version=options.fmi_version,
        fmi_interface=options.fmi_interface,
        step_size=options.step_size,
        can_handle_variable_communication_step_size=(
            export_spec.binary.can_handle_variable_communication_step_size()
        ),
        description=options.description,
    )
    xml: bytes = build_model_description(model)
    injector: FMUInjector = FMUInjector(
        binary_name=export_spec.binary.binary_name(),
        fmi_version=options.fmi_version,
        fmi_interface=options.fmi_interface,
        platforms=options.platforms,
    )
    destination: Path = Path(path)
    if destination.suffix.lower() != ".fmu":
        raise ValueError("FMU output path must end with .fmu")
        pass
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="fmu_", dir=destination.parent) as temporary:
        temporary_path: Path = Path(temporary)
        fmu_root: Path = temporary_path / "staging"
        fmu_root.mkdir()
        export_spec.export_artifacts_func(fmu_root)
        resources: Path = fmu_root / "resources"
        for name in export_spec.binary.required_resources():
            resource: Path = resources / name
            if not resource.is_file() or resource.stat().st_size == 0:
                raise FileNotFoundError(f"FMU resource is missing or empty: {resource}")
                pass
            pass
        (fmu_root / "modelDescription.xml").write_bytes(xml)
        injector.inject(fmu_root, model_identifier=options.model_identifier)
        archive: Path = temporary_path / "output.fmu"
        with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
            for file in sorted(fmu_root.rglob("*")):
                if file.is_file():
                    output.write(file, arcname=file.relative_to(fmu_root).as_posix())
                    pass
                pass
            pass
        with zipfile.ZipFile(archive) as output:
            if output.testzip() is not None:
                raise ValueError("FMU archive failed its integrity check")
                pass
            if "modelDescription.xml" not in output.namelist():
                raise ValueError("FMU archive has no modelDescription.xml")
                pass
            ElementTree.fromstring(output.read("modelDescription.xml"))
            pass
        os.replace(archive, destination)
        pass
    return destination
    pass
