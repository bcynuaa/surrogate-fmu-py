from __future__ import annotations

from typing import Sequence, Dict, Any, Self, Protocol

from .arrays import Array, ArrayOrTensor

'''
procedure:

import surrogate_fmu_py as sfpy

train_dbs: Sequence[DataBlockLike] = ... # prepare train data blocks
validation_dbs: Sequence[DataBlockLike] = ... # prepare validation data blocks
test_dbs: Sequence[DataBlockLike] = ... # prepare test data blocks
outside_params: Dict[str, Any] = ... # prepare outside params
reporter: ReporterLike = ... # prepare reporter

alg: AlgorithmLike = sfpy.algorithm("dnn") # take dnn as example
params: Dict[str, Any] = alg.format_params(overrides=outside_params) # format params with outside params
coder: CoderLike = alg.create_coder(datablocks=train_dbs, params=params) # create coder with train data blocks and params
core: CoreLike = alg.create_core(params=params) # create core with params
pipeline: PipelineLike = alg.create_pipeline(coder=coder, core=core, params=params) # create pipeline with coder, core and params

train_ds: DatasetLike = alg.create_dataset(datablocks=train_dbs, params=params) # create train dataset with train data blocks and params
validation_ds: DatasetLike = alg.create_dataset(datablocks=validation_dbs, params=params) # create validation dataset with validation data blocks and params
trainer: TrainerLike = alg.create_trainer(params=params) # create trainer with params

trainer.train(pipeline=pipeline, train_dataset=train_ds, validation_dataset=validation_ds, reporter=reporter) # train with pipeline, train dataset, validation dataset and reporter
model_path: str = "model.surr"
pipeline.save(model_path) # save pipeline to model path
pl: PipelineLike = sfpy.load(model_path) # load pipeline from model path

validator: ValidatorLike = alg.create_validator(params=params) # create validator with params
metrics: MetricsLike = validator.validate(pipeline=pl, validation_dataset=validation_ds, reporter=reporter) # validate with pipeline, validation dataset and reporter

tester: TesterLike = alg.create_tester(params=params) # create tester with params, the most different part from validator is that tester will make rollouts for sequence / continuous model
test_ds: DatasetLike = alg.create_dataset(datablocks=test_dbs, params=params) # create test dataset with test data blocks and params
metrics: MetricsLike = tester.test(pipeline=pl, test_dataset=test_ds, reporter=reporter) # test with pipeline, test dataset and reporter

# TODO:
pipeline.export_fmu("model.fmu", fmu_settings=...) # export pipeline to fmu with fmu settings
'''


class DataBlockLike(Protocol): # data block for train / validation / test
    def x(self) -> Array: ...
    def y(self) -> Array: ...
    def t(self) -> Array: ...
    pass


class ScalerLike(Protocol): # scaler for input / output normalization
    def init(self, shift: ArrayOrTensor, scale: ArrayOrTensor) -> Self: ...
    def shift(self) -> ArrayOrTensor: ...
    def scale(self) -> ArrayOrTensor: ...
    def dim(self) -> int: ...
    def encode(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def decode(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def to_numpy(self) -> Self: ...
    def to_torch(self) -> Self: ...
    pass


class ReporterLike(Protocol): ... # reporter for surrogate model


class CoderLike(Protocol): # encode inputs / decode outputs
    def init(self, input_scaler: ScalerLike, output_scaler: ScalerLike) -> Self: ...
    def encode(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def decode(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def encode_input(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def encode_output(self, x: ArrayOrTensor) -> ArrayOrTensor: ...
    def to_numpy(self) -> Self: ...
    def to_torch(self) -> Self: ...
    def input_dim(self) -> int: ...
    def output_dim(self) -> int: ...
    def save(self, path: str) -> Self: ...
    def load(self, path: str) -> Self: ...
    pass


class CoreLike(Protocol): # core surrogate model on normalized space
    def init(self, **kwargs: Any) -> Self: ...
    def predict(self, x: Array) -> Array: ...
    def save(self, path: str) -> Self: ...
    def load(self, path: str) -> Self: ...
    def train_mode(self) -> Self: ...
    def eval_mode(self) -> Self: ...
    pass


class DatasetLike(Protocol): # dataset for train / validation / test
    def feed(self, datablock: DataBlockLike) -> None: ...
    def finalize(self) -> None: ...
    pass


class PipelineLike(Protocol): # pipeline for surrogate model with coder and core
    def init(self, coder: CoderLike, core: CoreLike, params: Dict[str, Any]) -> Self: ...
    def predict(self, x: Array) -> Array: ...
    pass


class TrainerLike(Protocol): # trainer for surrogate model
    def train(self, pipeline: PipelineLike, train_dataset: DatasetLike, validation_dataset: DatasetLike, reporter: ReporterLike) -> PipelineLike: ...
    pass


class ValidatorLike(Protocol): # validator for surrogate model
    def validate(self, pipeline: PipelineLike, validation_dataset: DatasetLike, reporter: ReporterLike) -> MetricsLike: ...
    pass



class TesterLike(Protocol): # tester for surrogate model
    def test(self, pipeline: PipelineLike, test_dataset: DatasetLike, reporter: ReporterLike) -> MetricsLike: ...
    pass


class MetricsLike(Protocol): ... # metrics for surrogate model


class AlgorithmLike(Protocol): # algorithm for surrogate model
    def default_params(self) -> Dict[str, Any]: ...
    def format_params(self, overrides: Dict[str, Any]) -> Dict[str, Any]: ...
    def create_coder(self, datablocks: Sequence[DataBlockLike], params: Dict[str, Any]) -> CoderLike: ...
    def create_core(self, params: Dict[str, Any]) -> CoreLike: ...
    def create_dataset(self, datablocks: Sequence[DataBlockLike], params: Dict[str, Any]) -> DatasetLike: ...
    def create_pipeline(self, coder: CoderLike, core: CoreLike, params: Dict[str, Any]) -> PipelineLike: ...
    def create_trainer(self, params: Dict[str, Any]) -> TrainerLike: ...
    def create_validator(self, params: Dict[str, Any]) -> ValidatorLike: ...
    def create_tester(self, params: Dict[str, Any]) -> TesterLike: ...
    pass